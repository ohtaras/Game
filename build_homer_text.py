def tokenize(text):
    """Extract Greek words (3+ chars, letters only)."""
    tokens = re.findall(r'[α-ωΑ-Ωα-ωάέήίόύώΆΈΉΊΌΎΏ]+', text)
    out = []
    for t in tokens:
        t = t.lower().strip()
        if len(t) >= 3:
            out.append(t)
    return out

