# ── Simulate with time-bias selection ─────────────────────────────────────
def sim_timebias(i, cfg):
    hour=draw_hours[i]
    entry=by_row_first[i]
    picks=[]
    used_rows=set()
    for g in range(10):
        count=cfg[g]
        if count==0: continue
        # For each row: pick candidate with highest TIME_BIAS[n][hour]
        by_row={}
        for r,cands in entry[g].items():
            best=max(cands, key=lambda n: TIME_BIAS[n][hour] if TIME_BIAS[n] else 0)
            by_row[r]=best
        rows=(sorted(r for r in by_row if r not in used_rows)+
              sorted(r for r in by_row if r in used_rows))
        picked=0
        for r in rows:
            if picked>=count: break
            picks.append(by_row[r])
            used_rows.add(r)
            picked+=1
    return frozenset(picks)

def sim_no_bias(i, cfg):
    """Baseline: pick lowest-numbered candidate per row (no time bias)."""
    entry=by_row_first[i]
    picks=[]
    used_rows=set()
    for g in range(10):
        count=cfg[g]
        if count==0: continue
        by_row={r:min(cands) for r,cands in entry[g].items()}
        rows=(sorted(r for r in by_row if r not in used_rows)+
              sorted(r for r in by_row if r in used_rows))
        picked=0
        for r in rows:
            if picked>=count: break
            picks.append(by_row[r])
            used_rows.add(r)
            picked+=1
    return frozenset(picks)

